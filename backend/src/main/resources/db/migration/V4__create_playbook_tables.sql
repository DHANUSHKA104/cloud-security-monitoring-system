CREATE TABLE playbook_executions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category VARCHAR(100) NOT NULL,
    incident_id UUID NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE playbook_step_progress (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    execution_id BIGINT NOT NULL,
    step_title VARCHAR(255) NOT NULL,
    description VARCHAR(1000),
    status VARCHAR(30) NOT NULL DEFAULT 'PENDING',

    CONSTRAINT fk_playbook_execution
        FOREIGN KEY (execution_id)
        REFERENCES playbook_executions(id)
        ON DELETE CASCADE
);

CREATE INDEX idx_playbook_execution_incident
    ON playbook_executions(incident_id);

CREATE INDEX idx_playbook_progress_execution
    ON playbook_step_progress(execution_id);